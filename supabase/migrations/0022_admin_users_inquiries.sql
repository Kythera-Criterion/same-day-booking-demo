-- 0022：運営の画面のデザイン案に合わせた機能のうち、データベースが要るもの
--   1. ユーザー：お客様のアカウントの一覧（運営だけ。メールアドレスと電話番号は一部を伏せる）
--   2. 問い合わせ：お客様・サロンから運営への問い合わせ（受付番号つき）。運営が「未対応・対応中・解決済み」を付け、メモを残す
-- 2回流しても壊れない

-- ---------- 1. ユーザー ----------
-- お客様（サロンのスタッフ・運営を除く）。予約の数・来店・無断キャンセル・予約停止中かどうか
create or replace function public.admin_list_users(p_query text default null)
returns table (
  id uuid,
  display_name text,
  email_masked text,
  phone_masked text,
  gender text,
  age_group text,
  area_name text,
  created_at timestamptz,
  bookings int,
  completed int,
  no_shows int,
  last_booking_at timestamptz,
  suspended_until timestamptz
)
language plpgsql stable security definer set search_path = public
as $$
declare
  v_q text := nullif(btrim(coalesce(p_query, '')), '');
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  return query
  select p.id,
         p.display_name,
         case when coalesce(p.email, u.email) is null then null
              else left(coalesce(p.email, u.email), 1) || '***@' || split_part(coalesce(p.email, u.email), '@', 2) end,
         case when p.phone is null then null
              else repeat('*', greatest(length(public.norm_phone(p.phone)) - 4, 0)) || right(public.norm_phone(p.phone), 4) end,
         p.gender,
         p.age_group,
         a.name,
         p.created_at,
         (select count(*)::int from public.bookings b where b.user_id = p.id and b.status not like 'cancelled%'),
         (select count(*)::int from public.bookings b where b.user_id = p.id and b.status = 'completed'),
         (select count(*)::int from public.bookings b where b.user_id = p.id and b.status = 'no_show'),
         (select max(b.created_at) from public.bookings b where b.user_id = p.id),
         case when p.phone is null then null else public.suspension_until(public.norm_phone(p.phone)) end
  from public.profiles p
  join auth.users u on u.id = p.id
  left join public.areas a on a.id = p.area_id
  where not exists (select 1 from public.salon_members m where m.user_id = p.id)
    and not exists (select 1 from public.admins x where x.user_id = p.id)
    and (v_q is null or p.display_name ilike '%' || v_q || '%' or coalesce(p.email, u.email) ilike '%' || v_q || '%')
  order by p.created_at desc
  limit 300;
end;
$$;
revoke execute on function public.admin_list_users(text) from public, anon;
grant execute on function public.admin_list_users(text) to authenticated;

-- ---------- 2. 問い合わせ ----------
create table if not exists public.inquiries (
  id            uuid primary key default gen_random_uuid(),
  no            bigint generated by default as identity (start with 1001) unique,
  from_role     text not null check (from_role in ('user', 'salon')),
  user_id       uuid references auth.users(id) on delete set null,
  salon_id      uuid references public.salons(id) on delete set null,
  category      text not null check (category in ('booking', 'account', 'listing', 'other')),
  subject       text not null check (char_length(subject) between 1 and 80),
  body          text not null check (char_length(body) between 1 and 2000),
  booking_no    text check (booking_no is null or char_length(booking_no) <= 20),
  contact_email text,
  status        text not null default 'open' check (status in ('open', 'in_progress', 'resolved')),
  admin_note    text check (admin_note is null or char_length(admin_note) <= 2000),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  resolved_at   timestamptz
);
create index if not exists inquiries_status_idx on public.inquiries (status, created_at desc);
create index if not exists inquiries_user_idx on public.inquiries (user_id, created_at desc);

alter table public.inquiries enable row level security;
-- 読めるのは、送った本人・そのお店のスタッフ（お店から送ったもの）・運営。書き込みは下の関数から
drop policy if exists inquiries_select on public.inquiries;
create policy inquiries_select on public.inquiries
  for select using (
    user_id = auth.uid()
    or (from_role = 'salon' and salon_id is not null and public.is_salon_member(salon_id))
    or public.is_admin()
  );

-- 送る（お客様・サロン）。1人1日10件まで
create or replace function public.submit_inquiry(
  p_from_role  text,
  p_salon_id   uuid,
  p_category   text,
  p_subject    text,
  p_body       text,
  p_booking_no text default null
)
returns public.inquiries
language plpgsql security definer set search_path = public
as $$
declare
  q public.inquiries;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  if p_from_role not in ('user', 'salon') then raise exception 'invalid_input'; end if;
  if p_from_role = 'salon' and (p_salon_id is null or not public.is_salon_member(p_salon_id)) then raise exception 'forbidden'; end if;
  if coalesce(btrim(p_subject), '') = '' or coalesce(btrim(p_body), '') = '' then raise exception 'invalid_input'; end if;
  if (select count(*) from public.inquiries where user_id = auth.uid() and created_at > now() - interval '1 day') >= 10 then
    raise exception 'too_many_inquiries';
  end if;
  insert into public.inquiries (from_role, user_id, salon_id, category, subject, body, booking_no, contact_email)
  values (p_from_role, auth.uid(), case when p_from_role = 'salon' then p_salon_id end, p_category,
          left(btrim(p_subject), 80), left(btrim(p_body), 2000), nullif(left(btrim(coalesce(p_booking_no, '')), 20), ''),
          (select email from auth.users where id = auth.uid()))
  returning * into q;
  return q;
end;
$$;

-- 運営：状態とメモを変える（操作の記録に残す）
create or replace function public.admin_update_inquiry(p_id uuid, p_status text, p_note text default null)
returns public.inquiries
language plpgsql security definer set search_path = public
as $$
declare
  q public.inquiries;
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  if p_status not in ('open', 'in_progress', 'resolved') then raise exception 'invalid_input'; end if;
  update public.inquiries
  set status = p_status,
      admin_note = nullif(left(btrim(coalesce(p_note, '')), 2000), ''),
      updated_at = now(),
      resolved_at = case when p_status = 'resolved' then coalesce(resolved_at, now()) else null end
  where id = p_id
  returning * into q;
  if not found then raise exception 'inquiry_not_found'; end if;
  insert into public.audit_logs (actor, action, target_id) values (auth.uid(), 'update_inquiry', p_id);
  return q;
end;
$$;
revoke execute on function public.submit_inquiry(text, uuid, text, text, text, text) from public, anon;
revoke execute on function public.admin_update_inquiry(uuid, text, text) from public, anon;
grant execute on function public.submit_inquiry(text, uuid, text, text, text, text) to authenticated;
grant execute on function public.admin_update_inquiry(uuid, text, text) to authenticated;

-- 新しい問い合わせを、運営の画面へすぐ届ける（Realtime）
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'inquiries'
     ) then
    alter publication supabase_realtime add table public.inquiries;
  end if;
end;
$$;
